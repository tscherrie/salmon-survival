export type Language = 'de' | 'en';

const dictionaries: Record<Language, Record<MessageKey, string>> = { de, en };

const EN_MODALITY_LABELS: Record<Modality, string> = {
  director: 'Director',
  text: 'Text',
  image: 'Image',
  video: 'Video',
  lipsync: 'Lipsync',
  voice: 'Voice',
  music: 'Music',
  sound: 'Sound',
  tools: 'Tools',
};

let currentLanguage: Language = 'de';
const listeners = new Set<() => void>();

export function getLanguage(): Language {
  return currentLanguage;
}

export function setLanguage(language: Language): void {
  if (language === currentLanguage) return;
  currentLanguage = language;
  if (typeof document !== 'undefined') document.documentElement.lang = language;
  for (const l of listeners) l();
}

/** Übersetzt einen Schlüssel; `{name}` wird durch `vars.name` ersetzt. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[currentLanguage][key] ?? de[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/** Beschriftung einer Modalität (de: aus @studio/core). */
export function modalityLabel(modality: Modality): string {
  return currentLanguage === 'de' ? MODALITY_LABELS[modality] : EN_MODALITY_LABELS[modality];
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** React-Hook: liefert `t` und rendert bei Sprachwechsel neu. */
export function useT(): typeof t {
  useSyncExternalStore(subscribe, getLanguage, getLanguage);
  return t;
}

export function useLanguage(): Language {
  return useSyncExternalStore(subscribe, getLanguage, getLanguage);
}

/** Datum/Zeit kurz formatiert, z. B. „01.10., 14:32“. */
export function formatDateTime(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return new Intl.DateTimeFormat(currentLanguage === 'de' ? 'de-DE' : 'en-GB', {
    day: '2-digit',
    month: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
  }).format(date);
}
